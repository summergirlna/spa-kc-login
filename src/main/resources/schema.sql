CREATE TABLE IF NOT EXISTS registration_attempts (
    registration_id VARCHAR(36) PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    confirmation_code VARCHAR(6) NOT NULL,
    status VARCHAR(30) NOT NULL,
    verified_at TIMESTAMP WITH TIME ZONE NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_registration_attempts_email
    ON registration_attempts (email);

CREATE INDEX IF NOT EXISTS idx_registration_attempts_expires_at
    ON registration_attempts (expires_at);

CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    keycloak_user_id VARCHAR(100) UNIQUE,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);